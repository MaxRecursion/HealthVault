const definitionById = new Map<string, BiomarkerDefinition>(biomarkerCatalog.map((item) => [item.id, item]));

export function readBiomarker(report: BloodReport, id: BiomarkerId): BiomarkerResult {
  const definition = definitionById.get(id);
  if (!definition) throw new Error(`Unknown biomarker ID: ${id}`);
  const measurement = report.measurements[id];
  return {
    ...definition,
    value: measurement?.value ?? null,
    unit: measurement?.unit ?? definition.unit,
    sourceDate: report.date,
    sourceLabel: report.shortLabel,
    referenceRange: measurement?.referenceRange ?? null,
    reportedStatus: measurement?.reportedStatus ?? null,
  };
}

export function getReportResults(report: BloodReport): BiomarkerResult[] {
  return biomarkerCatalog.map((definition) => readBiomarker(report, definition.id));
}

export function findBiomarker(id: BiomarkerId): BiomarkerDefinition {
  const definition = definitionById.get(id);
  if (!definition) throw new Error(`Unknown biomarker ID: ${id}`);
  return definition;
}

export function getReportById(id: string): BloodReport | undefined {
  return reports.find((report) => report.id === id);
}
