const ref = (
  label: string,
  lower?: number,
  upper?: number,
  options: Pick<ReferenceRange, "lowerInclusive" | "upperInclusive" | "bands"> = {},
): ReferenceRange => ({
  label,
  ...(lower !== undefined ? { lower } : {}),
  ...(upper !== undefined ? { upper } : {}),
  ...options,
});

const band = (
  label: string,
  status: RangeBand["status"],
  lower?: number,
  upper?: number,
  lowerInclusive = true,
  upperInclusive = true,
): RangeBand => ({
  label,
  status,
  ...(lower !== undefined ? { lower } : {}),
  ...(upper !== undefined ? { upper } : {}),
  lowerInclusive,
  upperInclusive,
});

const result = (value: number, unit: string, referenceRange: ReferenceRange | null): ReportMeasurement => ({
  value,
  unit,
  referenceRange,
  reportedStatus: null,
});

